// A faster start (src/ui/title.js, src/main.js, src/data/world.js and the
// world's helpers): how long the Enter button takes on a slow phone.
//  - The world is generated exactly as before, only faster (its hash below).
//  - Behind the painted sky the title's camera tour is never seen, so the
//    later shots aren't glanced at while loading, and the world isn't drawn
//    once the sky has faded in, until the camera comes back to the player.
//  - The opening shot is framed as it will be seen from its first frame (zoom
//    and depth-view tilt), so its pictures are asked for in one go.
//  - A townsperson's idle parts are asked for with their picture.
// Its own file, so the stub Image below is in place before any picture is asked for.
import './seed.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';

const asked = [];
globalThis.Image = class { constructor() { this.complete = false; this.naturalWidth = 0; asked.push(this); } };
const { buildWorld } = await import('../src/data/world.js');
const { TitleScreen, TITLE_SHOTS, SKY_IN_MS, worldOutOfSight, titleCameraAt } = await import('../src/ui/title.js');
const { depthTarget } = await import('../src/render/depthview.js');
const { drawCreature, townIdleParts } = await import('../src/render/sprites.js');
const { TILE } = await import('../src/config.js');

// The whole generated world, typed arrays and all, as one hash.
const worldHash = (w) => createHash('sha256').update(JSON.stringify(w, (k, v) => (ArrayBuffer.isView(v) ? Array.from(v) : v))).digest('hex');

test('the world is generated byte for byte as before', () => {
  // Hashes of the world as generated before the start-up was sped up (Nov
  // 2026). A speed-up must leave them alone. A deliberate change to the world
  // (new spawns, objects, regions) changes them too: then check the change is
  // the one intended and paste the new hash here.
  const why = 'the generated world changed: fine for a deliberate change to the world (update the hash), never for a speed-up';
  // (Changed on purpose for Diving's reefs and Archaeology's dig sites and museum, placed last:
  // src/data/divereefs.js, src/data/digsites.js. The world without the late additions, below, is untouched.)
  assert.equal(worldHash(buildWorld()), '3ad226055cf432853a9b2a67a0645d2480593354fc3258d4b8f935f3d5d822cb', why);
  assert.equal(worldHash(buildWorld({ groves: false })), '59dd730d7829bafb308efe895de87948a9a90ac695f04faa662fb4e3005d4c02', why);
});

test('the world counts as out of sight only under the painted sky, once it has faded in', () => {
  const base = { ready: true, skyIn: true, sinceReady: SKY_IN_MS, handedBack: false };
  assert.equal(worldOutOfSight(base), true);
  assert.equal(worldOutOfSight({ ...base, ready: false }), false, 'loading: drawn, so its pictures are asked for');
  assert.equal(worldOutOfSight({ ...base, sinceReady: SKY_IN_MS - 1 }), false, 'the sky is still fading in over it');
  assert.equal(worldOutOfSight({ ...base, skyIn: false }), false, 'no painted sky (or it failed to load): the tour shows');
  assert.equal(worldOutOfSight({ ...base, handedBack: true }), false, 'back with the player: drawn again');
  assert.ok(SKY_IN_MS >= 1250 + 100, 'longer than the cream fade (0.1 + 1.1 s) and the sky fade (0.15 + 1.1 s)');
});

/** A title on a stand-in page with its pictures all in (and, when `sky`, the
 *  painted sky up), run at `dt` ms a frame until the Enter button shows. */
function stageTitle({ sky = true, still = false } = {}) {
  const cls = (init = []) => { const s = new Set(init); return { add: (...c) => c.forEach((x) => s.add(x)), remove: (...c) => c.forEach((x) => s.delete(x)), contains: (c) => s.has(c), toggle() {} }; };
  const splash = { classList: cls(sky ? ['title-painted'] : []), querySelector: () => null, style: { setProperty() {} } };
  const t = new TitleScreen(splash, { still, lowFx: true });
  t.tracker.job('pictures'); t.tracker.done('pictures');
  if (sky) t._sky = { complete: true, naturalWidth: 1600 };
  const cam = { cx: 0, cy: 0, tilt: 0, zoomMul: 1, setZoomMul(k) { this.zoomMul = k; }, snapped: true };
  t.game = { camera: cam };
  return { t, cam };
}
function withPage(fn) {
  const saved = globalThis.document;
  globalThis.document = { body: { classList: { add() {}, remove() {}, contains: () => false } } };
  try { return fn(); } finally { globalThis.document = saved; }
}

test('under the painted sky the later shots are never glanced at, and the button shows with a full bar', () => {
  withPage(() => {
    const { t, cam } = stageTitle();
    const spots = [];
    let frames = 0;
    while (!t.ready && frames < 200) { t.frame(250); frames++; spots.push([cam.cx / TILE, cam.cy / TILE]); }
    assert.ok(t.ready);
    for (const s of TITLE_SHOTS.slice(1)) assert.ok(!spots.some(([x, y]) => x === s.from[0] && y === s.from[1]), `${s.name} not glanced at`);
    // Two opening frames and the bar's ease, then ready in the frame the bar fills.
    assert.ok(frames <= 2 + 3, `${frames} frames`);
  });
});

test('the opening frames frame the first shot as it will be seen: its zoom and the depth view tilt', () => {
  withPage(() => {
    const { t, cam } = stageTitle();
    t.frame(16);
    const v = titleCameraAt(0, TITLE_SHOTS, false);
    assert.equal(cam.cx, TITLE_SHOTS[0].from[0] * TILE);
    assert.equal(cam.zoomMul, v.zoom, 'the zoom the shot opens at (not 1, then a wider view a frame later)');
    assert.equal(cam.tilt, depthTarget(t.game, cam), 'tilted already (the renderer would ease it in over a dozen frames)');
    assert.ok(cam.tilt > 0);
  });
});

test('the world is hidden once the sky is in, and drawn again when the camera goes back to the player', () => {
  withPage(() => {
    const { t } = stageTitle({ still: true });
    while (!t.ready) t.frame(250);
    assert.equal(t.worldHidden, false, 'the cream and sky are still fading: the world shows through');
    let ms = 0;
    while (ms < SKY_IN_MS) { t.frame(100); ms += 100; }
    assert.equal(t.worldHidden, true);
    // Enter: with Reduce motion the swap is at once.
    t.exit();
    assert.equal(t.worldHidden, false, 'drawn again as the title goes');
  });
  withPage(() => {
    const { t } = stageTitle({ sky: false });
    while (!t.ready) t.frame(250);
    for (let i = 0; i < 40; i++) t.frame(100);
    assert.equal(t.worldHidden, false, 'without the painted sky the tour behind the title is seen');
  });
});

test('a townsperson asks for their idle parts with their picture, not a round trip later', () => {
  const ctx = new Proxy({}, { get: (o, k) => (k in o ? o[k] : () => {}), set: (o, k, v) => { o[k] = v; return true; } });
  const n = asked.length;
  try { drawCreature(ctx, 'banker', 0, 0, { time: 0 }); } catch { /* headless: nothing to draw into */ }
  const srcs = asked.slice(n).map((i) => i.src);
  assert.ok(srcs.some((s) => s.endsWith('townsfolk/banker.webp')), 'the picture');
  const parts = townIdleParts('banker');
  assert.ok(parts.length > 1);
  for (const p of parts) assert.ok(srcs.some((s) => s.endsWith(`banker_${p}.webp`)), `${p} asked for at once`);
  // Low graphics never draws the idle parts, so never asks for them.
  const m = asked.length;
  try { drawCreature(ctx, 'farmer', 0, 0, { time: 0, low: true }); } catch { /* as above */ }
  assert.ok(!asked.slice(m).some((i) => /farmer_/.test(i.src)));
});

test('one shared number formatter writes the same as toLocaleString (compendium.js)', () => {
  const f = new Intl.NumberFormat('en-GB');
  for (const x of [0, 1, 2.5, 12.345, 1234, 1234567.891, -3.2, 0.0004, 99.9999]) assert.equal(f.format(x), x.toLocaleString('en-GB'));
});
