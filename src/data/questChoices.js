// box, and waits in the journal (and with a line's giver) until you make it.
// Both answers finish the same way: nothing in the story is ever locked.
//
// Rewards work like the moral encounters (moralEvents.js), lopsided on
// purpose: evil pays coins (scaled with your fight level, moralCoins) and
// sometimes loot; good pays a share of a skill level in XP, shrine points or
// the Blessed buff. Chapter choices weigh a little more as the story goes on.
//
// Fields:
//   who      who asks (a townsperson or quest giver id); their portrait shows
//   title    a short name for the journal; `text` sets the scene
//   good / evil: { label (no sun/moon or "(Good)": added for you), karma,
//     skill?, xp? (share of a level), shrine?, bless?, coins?, items? [[id, qty]],
//     outcome (what happens), react (`who` answers: the next line changes),
//     done (the journal's "You ..." once chosen), after? (a line's giver
//     says this from then on, in place of their thanks) }

